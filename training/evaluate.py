import argparse
from pathlib import Path

import torch
from torch.utils.data import DataLoader

from training.model import TinyGPT
from training.tokenizer import ByteTokenizer
from training.train import collate, make_windows, read_examples, run_epoch


@torch.inference_mode()
def complete(model: TinyGPT, tokenizer: ByteTokenizer, prompt: str, max_tokens: int) -> str:
    tokens = [tokenizer.bos_id, *tokenizer.encode(prompt)]
    generated = []
    for _ in range(max_tokens):
        context = torch.tensor([tokens[-model.context_length :]])
        logits = model(context)[0, -1]
        logits[tokenizer.bos_id] = -torch.inf
        token = logits.argmax().item()
        if token == tokenizer.eos_id:
            break
        tokens.append(token)
        generated.append(token)
    return tokenizer.decode(generated, errors="replace")


def main() -> None:
    parser = argparse.ArgumentParser(description="Evaluate a saved TinyGPT checkpoint on CPU.")
    parser.add_argument("--checkpoint", type=Path, default=Path("models/tiny-gpt.pt"))
    parser.add_argument("--validation", type=Path, default=Path("training/validation.txt"))
    parser.add_argument("--prompt", help="Also generate a greedy continuation of this text.")
    parser.add_argument("--qa", action="store_true", help="Generate and score answers for held-out Q&A lines.")
    parser.add_argument("--max-tokens", type=int, help="Maximum generated byte tokens (40 normally, 80 with --qa).")
    args = parser.parse_args()
    if args.max_tokens is not None and args.max_tokens < 1:
        parser.error("--max-tokens must be at least 1.")
    max_tokens = args.max_tokens if args.max_tokens is not None else (80 if args.qa else 40)

    try:
        checkpoint = torch.load(args.checkpoint, map_location="cpu", weights_only=True)
        examples = read_examples(args.validation)
    except (OSError, ValueError) as error:
        parser.error(str(error))
    if args.qa and any(
        not line.startswith("Question: ") or not line.partition(" Answer: ")[2].strip()
        for line in examples
    ):
        parser.error("--qa requires lines formatted as Question: … Answer: …")

    model = TinyGPT()
    model.load_state_dict(checkpoint["model_state"])
    tokenizer = ByteTokenizer()
    loader = DataLoader(
        make_windows(examples, tokenizer, model.context_length), batch_size=16, collate_fn=collate
    )
    loss = run_epoch(model, loader, "cpu")
    print(f"Epoch {checkpoint['epoch']} checkpoint | {len(examples)} validation examples | loss {loss:.4f}")
    if args.qa:
        exact_matches = 0
        for example in examples:
            question, _, expected = example.partition(" Answer: ")
            answer = complete(model, tokenizer, f"{question} Answer:", max_tokens).strip()
            exact_matches += answer == expected
            print(f"{question}\n  Generated: {answer or '(empty)'}\n  Expected:  {expected}")
        print(f"Exact answers: {exact_matches}/{len(examples)}")
    if args.prompt is not None:
        continuation = complete(model, tokenizer, args.prompt, max_tokens)
        print(f"Prompt: {args.prompt!r}")
        print(f"Continuation: {continuation!r}")


if __name__ == "__main__":
    main()
